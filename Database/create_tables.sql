/*==========================================================
SECTION 1 : PATIENTS TABLE
Stores patient demographic and registration information.
==========================================================*/

CREATE TABLE IF NOT EXISTS patients (

    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_name VARCHAR(100) NOT NULL,

    age INTEGER CHECK (age >= 0),

    gender VARCHAR(20),

    city VARCHAR(50),

    province VARCHAR(50),

    registration_date DATE

);

/*==========================================================
SECTION 2 : DOCTORS TABLE
Stores healthcare provider information.
==========================================================*/

CREATE TABLE IF NOT EXISTS doctors (

    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    doctor_name VARCHAR(100) NOT NULL,

    specialization VARCHAR(100),

    department VARCHAR(100),

    experience_years INTEGER CHECK (experience_years >= 0)

);

/*==========================================================
SECTION 3 : APPOINTMENTS TABLE
Stores patient appointment records.
==========================================================*/

CREATE TABLE IF NOT EXISTS appointments (

    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_id INTEGER NOT NULL,

    doctor_id INTEGER NOT NULL,

    appointment_date DATE NOT NULL,

    appointment_status VARCHAR(50) NOT NULL
        CHECK (appointment_status IN ('Scheduled', 'Completed', 'Cancelled')),

    visit_type VARCHAR(50) NOT NULL,


    CONSTRAINT fk_patient

        FOREIGN KEY (patient_id)

        REFERENCES patients(patient_id),


    CONSTRAINT fk_doctor

        FOREIGN KEY (doctor_id)

        REFERENCES doctors(doctor_id)

);

/*==========================================================
SECTION 4 : TREATMENTS TABLE
Stores medical treatment details and costs.
==========================================================*/

CREATE TABLE IF NOT EXISTS treatments (

    treatment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    appointment_id INTEGER NOT NULL UNIQUE,

    treatment_name VARCHAR(100),

    treatment_category VARCHAR(100),

    treatment_cost NUMERIC(10,2) NOT NULL CHECK (treatment_cost >= 0),


    CONSTRAINT fk_appointment

        FOREIGN KEY (appointment_id)

        REFERENCES appointments(appointment_id)

);

/*==========================================================
SECTION 5 : BILLING TABLE
Stores healthcare billing and payment information.
==========================================================*/

CREATE TABLE IF NOT EXISTS billing (

    bill_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_id INTEGER NOT NULL,

    treatment_id INTEGER NOT NULL UNIQUE,

    billing_date DATE NOT NULL,

    total_amount NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),

    payment_status VARCHAR(50) NOT NULL
        CHECK (payment_status IN ('Paid', 'Pending', 'Cancelled')),

    payment_method VARCHAR(50) NOT NULL,


    CONSTRAINT fk_bill_patient

        FOREIGN KEY (patient_id)

        REFERENCES patients(patient_id),


    CONSTRAINT fk_bill_treatment

        FOREIGN KEY (treatment_id)

        REFERENCES treatments(treatment_id)

);

/*==========================================================
SECTION 6 : INSURANCE CLAIMS TABLE
Stores patient insurance claim information.
==========================================================*/

CREATE TABLE IF NOT EXISTS insurance_claims (

    claim_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    patient_id INTEGER NOT NULL,

    insurance_provider VARCHAR(100),

    claim_amount NUMERIC(10,2) NOT NULL CHECK (claim_amount >= 0),

    claim_status VARCHAR(50) NOT NULL
        CHECK (claim_status IN ('Approved', 'Pending', 'Rejected')),

    claim_date DATE NOT NULL,


    CONSTRAINT fk_claim_patient

        FOREIGN KEY (patient_id)

        REFERENCES patients(patient_id)

);

